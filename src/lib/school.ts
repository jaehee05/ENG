/**
 * 학교 이름을 정식 명칭으로 폅니다.
 *
 * 학생들은 "청담고", "선화예고" 처럼 줄여 적는다. 그대로 두면 같은 학교가
 * "청담고"와 "청담고등학교" 두 이름으로 갈려 학생 목록에서 묶이지 않는다.
 *
 * 줄임말은 뒤에 붙는 한 덩어리라 끝에서부터 맞춰 본다. 이때 "예고"는
 * "예고등학교"가 아니라 "예술고등학교"이므로, 종류가 붙은 것을 먼저 본다.
 */

/**
 * [줄임말, 정식 명칭] — 긴 것부터 본다.
 *
 * "국제고"·"마이스터고"처럼 줄임말을 펴도 결과가 같은 것(국제 + 고등학교)은
 * 넣지 않았다. 마지막 '고' 규칙이 알아서 처리한다.
 */
const SUFFIXES: [string, string][] = [
  ['여고', '여자고등학교'],
  ['남고', '남자고등학교'],
  ['예고', '예술고등학교'],
  ['과고', '과학고등학교'],
  ['외고', '외국어고등학교'],
  ['체고', '체육고등학교'],
  ['공고', '공업고등학교'],
  ['상고', '상업고등학교'],
  ['고', '고등학교'],
  ['여중', '여자중학교'],
  ['남중', '남자중학교'],
  ['중', '중학교'],
  ['초', '초등학교'],
]

/**
 * 이미 정식 명칭이면 그대로 둔다.
 *
 * '학교'로 끝나면 더 펼 것이 없다. 뒤에 '분교'·'부설' 같은 말이 붙는 경우도
 * 있어 '학교'가 들어 있기만 해도 손대지 않는다 — 어설프게 고치느니 둔다.
 */
function alreadyFull(name: string): boolean {
  return name.includes('학교')
}

/**
 * 입력한 학교 이름을 정식 명칭으로. 규칙에 안 맞으면 그대로 돌려준다.
 *
 * 정확한 교명을 맞히려는 것이 아니라 표기를 하나로 모으는 것이 목적이다.
 * 틀리게 펴진 경우는 관리자가 학생 정보 수정에서 고칠 수 있다.
 */
export function normalizeSchool(raw?: string | null): string {
  const name = (raw ?? '').trim().replace(/\s+/g, ' ')
  if (!name) return ''
  if (alreadyFull(name)) return name

  for (const [short, full] of SUFFIXES) {
    if (!name.endsWith(short)) continue
    const head = name.slice(0, -short.length)
    // 줄임말만 덜렁 적은 경우("고", "예고")는 학교 이름이 없는 것이라 손대지
    // 않는다. 펴 봐야 "고등학교"가 되어 어느 학교인지 알 수 없다.
    if (!head) return name
    return head + full
  }
  return name
}
